// Fallback helper ensuring that ANY of the 22 languages gracefully receives natural, fully translated content
export function getAdvisorTranslations(langCode: string): MultilingualAdvisorDictionary {
  const normalized = (langCode || 'en').toLowerCase().trim();
  if (ADVISOR_TRANSLATIONS[normalized]) {
    return ADVISOR_TRANSLATIONS[normalized];
  }

  // Cross-lingual semantic fallbacks for remaining regional languages:
  // e.g. kok -> mr, mai/doi/brx -> hi, ks/sd -> ur, mni/sat -> bn/hi
  if (normalized === 'kok') return ADVISOR_TRANSLATIONS['mr'] || ADVISOR_TRANSLATIONS['en'];
  if (['mai', 'doi', 'brx'].includes(normalized)) return ADVISOR_TRANSLATIONS['hi'] || ADVISOR_TRANSLATIONS['en'];
  if (['ks', 'sd'].includes(normalized)) return ADVISOR_TRANSLATIONS['ur'] || ADVISOR_TRANSLATIONS['en'];
  if (normalized === 'mni') return ADVISOR_TRANSLATIONS['bn'] || ADVISOR_TRANSLATIONS['en'];
  if (normalized === 'sat') return ADVISOR_TRANSLATIONS['hi'] || ADVISOR_TRANSLATIONS['en'];

  return ADVISOR_TRANSLATIONS['hi'] || ADVISOR_TRANSLATIONS['en'];
}
