/**
 * Deep merge fallback resolver:
 * Ensures that if any key or nested object is omitted in any regional dictionary,
 * it recursively falls back to translations.en rather than evaluating to undefined
 * and throwing runtime TypeError.
 */
export function deepMergeFallback<T>(target: unknown, fallback: T): T {
  if (target === undefined || target === null) return fallback;
  if (typeof fallback !== 'object' || fallback === null || Array.isArray(fallback)) {
    return (target !== undefined ? target : fallback) as T;
  }
  const fallbackRecord = fallback as Record<string, unknown>;
  const targetRecord = (typeof target === 'object' && target !== null ? target : {}) as Record<string, unknown>;
  const result: Record<string, unknown> = { ...fallbackRecord };
  for (const key of Object.keys(fallbackRecord)) {
    result[key] = deepMergeFallback(targetRecord[key], fallbackRecord[key]);
  }
  return result as T;
}

